"""Turn the result tables into LaTeX macros.

Every number quoted in the manuscript comes from here, so the text cannot drift
from the experiments. A macro with no backing result is emitted as \\PENDING,
which is impossible to miss in a compiled PDF.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code"))

from analysis.stats import holm, paired_bootstrap_diff    # noqa: E402

TAB = ROOT / "results" / "tables"
OUT = ROOT / "paper" / "numbers.tex"

TAG = {"turbid_fish": "Fish", "exdark": "ExDark", "kvasir": "Kvasir"}
PRETTY_OP = {"identity": "no enhancement", "hist_eq": "histogram equalisation",
             "clahe": "CLAHE", "gamma": "automatic gamma", "ssr": "SSR",
             "msrcr": "MSRCR", "gray_world": "grey-world", "dcp": "DCP",
             "unsharp": "unsharp masking", "zero_dce": "Zero-DCE"}
PRETTY_SCORE = {"iqa_brisque": "BRISQUE", "iqa_niqe": "NIQE",
                "iqa_entropy": "entropy", "iqa_rms_contrast": "RMS contrast",
                "iqa_colourfulness": "colourfulness",
                "iqa_sharpness": "sharpness", "iqa_eme": "EME",
                "iqa_uciqe": "UCIQE", "iqa_uiqm": "UIQM",
                "iqa_psnr_in": "PSNR to input", "iqa_ssim_in": "SSIM to input",
                "iqa_ambe": "AMBE", "iqa_loe": "LOE"}
LETTERS = str.maketrans({"_": "", "0": "Zero", "1": "One", "2": "Two",
                         "3": "Three", "4": "Four", "5": "Five", "6": "Six",
                         "7": "Seven", "8": "Eight", "9": "Nine"})


def read(pattern):
    files = sorted(TAB.glob(pattern))
    return pd.concat([pd.read_csv(f) for f in files], ignore_index=True) \
        if files else pd.DataFrame()


class Numbers(dict):
    def num(self, name, value, fmt="{:.2f}"):
        self[name] = r"\PENDING" if value is None or (
            isinstance(value, float) and not np.isfinite(value)) \
            else fmt.format(value)

    def pp(self, name, value):
        """A percentage-point quantity, from a fraction."""
        self.num(name, None if value is None else 100 * value, "{:.1f}")

    def word(self, name, value):
        self[name] = str(value) if value else r"\PENDING"

    def write(self, path):
        lines = [r"% Generated by code/analysis/make_numbers.py. Do not edit.",
                 r"\providecommand{\PENDING}{\textbf{??}}"]
        defined = {k.translate(LETTERS) for k in self}
        lines += [r"\newcommand{\%s}{%s}" % (k.translate(LETTERS), v)
                  for k, v in sorted(self.items())]

        # Any macro the manuscript uses but this run could not compute would
        # otherwise be an undefined control sequence, which still produces a
        # PDF under nonstopmode. Define it as a visible placeholder instead.
        used = set()
        for f in list((path.parent / "sections").glob("*.tex")) + \
                [path.parent / "main.tex"]:
            if f.exists():
                used |= set(re.findall(r"\\([A-Za-z]+)\{\}", f.read_text()))
        missing = sorted(used - defined)
        lines += [r"\providecommand{\%s}{\PENDING}" % m for m in missing]

        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n")
        pend = sum(v == r"\PENDING" for v in self.values()) + len(missing)
        print(f"wrote {len(self)} macros to {path} ({pend} PENDING)")
        if missing:
            print("  no result behind: " + ", ".join(missing))


def main():
    N = Numbers()
    acc = read("operator_accuracy__*.csv")
    sco = read("operator_scores__*.csv")
    sel = read("selection__*.csv")
    img = read("perimage__*.csv")
    sev = read("severity__*.csv")
    leak = read("leakage.csv")
    if acc.empty:
        sys.exit("no result tables yet")

    N.num("nDatasets", acc.dataset.nunique(), "{:d}")
    N.num("nBackbones", acc.backbone.nunique(), "{:d}")
    N.num("nOperators", acc.operator.nunique(), "{:d}")
    N.num("nFolds", acc.fold.nunique(), "{:d}")
    N.num("nSettings", len(acc.groupby(["dataset", "backbone"])), "{:d}")

    # ---- 1. the deployment penalty ---------------------------------------
    p1 = acc[acc.protocol == "P1_dropin"]
    p2 = acc[acc.protocol == "P2_retrained"]
    per = p1.groupby(["dataset", "backbone", "operator"]).accuracy.mean() \
        .unstack("operator")
    delta = per.sub(per["identity"], axis=0).drop(columns="identity")
    N.pp("maxDrop", -delta.min().min())
    N.pp("medianDrop", -delta.stack().median())
    N.num("fracHurt", float((delta.stack() < 0).mean()), "{:.2f}")
    N.num("pctHurt", 100 * float((delta.stack() < 0).mean()), "{:.0f}")
    worst = delta.stack().idxmin()
    N.word("worstOperator", PRETTY_OP.get(worst[-1], worst[-1]))
    N.num("nSettingsIdentityBest",
          int((per.idxmax(axis=1) == "identity").sum()), "{:d}")
    N.num("nSettingsTotal", len(per), "{:d}")

    for ds, d in p1.groupby("dataset"):
        t = TAG.get(ds, ds)
        m = d.groupby("operator").accuracy.mean()
        N.pp(f"acc{t}Identity", m.get("identity"))
        N.pp(f"acc{t}Worst", m.min())
        N.word(f"op{t}Worst", PRETTY_OP.get(m.idxmin(), m.idxmin()))
        N.pp(f"drop{t}Worst", m.get("identity") - m.min())

    # is each operator's loss real, or fold noise? paired across settings
    wide = (p1.groupby(["dataset", "backbone", "fold", "operator"])
            .accuracy.mean().unstack("operator").dropna())
    if "identity" in wide.columns and len(wide) >= 3:
        ops = [o for o in wide.columns if o != "identity"]
        diffs, pvals = [], []
        for o in ops:
            d, lo, hi, p = paired_bootstrap_diff(wide[o].to_numpy(),
                                                 wide["identity"].to_numpy())
            diffs.append(d)
            pvals.append(p)
        adj = holm(pvals)
        worse = [(o, d, q) for o, d, q in zip(ops, diffs, adj) if d < 0 and q < 0.05]
        better = [(o, d, q) for o, d, q in zip(ops, diffs, adj) if d > 0 and q < 0.05]
        N.num("nSigWorse", len(worse), "{:d}")
        N.num("nSigBetter", len(better), "{:d}")
        N.num("nOperatorsTested", len(ops), "{:d}")
        N.num("nPairedSettings", len(wide), "{:d}")
        if worse:
            N.word("sigWorseList", ", ".join(
                PRETTY_OP.get(o, o) for o, _, _ in sorted(worse, key=lambda r: r[1])))

    # ---- 2. the protocol gap ---------------------------------------------
    j = (p1.groupby(["dataset", "backbone", "fold", "operator"]).accuracy.mean()
         .rename("p1").to_frame().join(
             p2.groupby(["dataset", "backbone", "fold", "operator"])
             .accuracy.mean().rename("p2")))
    j = j.reset_index()
    j = j[j.operator != "identity"]
    N.pp("protocolGap", float((j.p2 - j.p1).mean()))
    N.num("nOperatorsReversed",
          int(((j.p1 < j.groupby(["dataset", "backbone", "fold"]).p1.transform("max"))
               & (j.p2 > j.p1)).sum()), "{:d}")
    gap_by = (j.assign(gap=j.p2 - j.p1).groupby("dataset").gap.mean())
    for ds, v in gap_by.items():
        N.pp(f"protocolGap{TAG.get(ds, ds)}", v)

    # ---- 3. what the scores can see --------------------------------------
    if not sco.empty:
        rho = (sco.groupby(["scorer", "dataset", "backbone", "fold"])
               .apply(lambda g: spearmanr(g.value, g.p1_accuracy).statistic,
                      include_groups=False).rename("rho").reset_index())
        mean_rho = rho.groupby("scorer").rho.mean()
        esp = mean_rho[mean_rho.index.str.startswith("esp_")]
        iqa = mean_rho[mean_rho.index.str.startswith("iqa_")]
        geo = mean_rho[mean_rho.index.str.startswith("geo_")]
        N.num("espRhoBest", esp.max())
        N.word("espBestName", esp.idxmax().replace("esp_", "").upper())
        N.num("espRhoMmd", mean_rho.get("esp_mmd", np.nan))
        N.num("geoRhoBest", geo.max() if len(geo) else np.nan)
        if len(iqa):
            N.num("iqaRhoBest", iqa.max())
            N.word("iqaBestName", PRETTY_SCORE.get(iqa.idxmax(), iqa.idxmax()))
            N.num("iqaRhoWorst", iqa.min())
            N.word("iqaWorstName", PRETTY_SCORE.get(iqa.idxmin(), iqa.idxmin()))
            N.num("iqaRhoUiqm", mean_rho.get("iqa_uiqm", np.nan))
            N.num("iqaRhoUciqe", mean_rho.get("iqa_uciqe", np.nan))
            # sharpness, the clearest per-dataset case
            per_ds = (rho[rho.scorer == "iqa_sharpness"]
                      .groupby("dataset").rho.mean())
            for ds, v in per_ds.items():
                N.num(f"sharpness{TAG.get(ds, ds)}", v)
            nr = [s for s in iqa.index
                  if s not in {"iqa_psnr_in", "iqa_ssim_in", "iqa_ambe", "iqa_loe"}]
            N.num("nNoRefNegative", int((iqa[nr] < 0).sum()), "{:d}")
            N.num("nNoRefTotal", len(nr), "{:d}")
            N.num("nInputRefTotal", len(iqa) - len(nr), "{:d}")
            N.num("nPixelMetrics", len(iqa), "{:d}")
            heavy = img[img.scorer.isin(["iqa_brisque", "iqa_niqe"])]
            if len(heavy):
                # images behind the smallest per-operator mean of a heavy metric
                N.num("nHeavySample",
                      int(heavy.n.min() / max(acc.operator.nunique(), 1)), "{:d}")
            N.num("iqaRhoBrisque", mean_rho.get("iqa_brisque", np.nan))
            N.num("iqaRhoNiqe", mean_rho.get("iqa_niqe", np.nan))
            # the metrics enhancement practice actually uses are the
            # no-reference ones; quote their best separately
            N.num("iqaNoRefRhoBest", iqa[nr].max())
            N.word("iqaNoRefBestName",
                   PRETTY_SCORE.get(iqa[nr].idxmax(), iqa[nr].idxmax()))
            # paired test: is ESP ahead of the best pixel metric?
            a = rho[rho.scorer == "esp_mmd"].set_index(
                ["dataset", "backbone", "fold"]).rho
            b = rho[rho.scorer == iqa.idxmax()].set_index(
                ["dataset", "backbone", "fold"]).rho
            common = a.index.intersection(b.index)
            if len(common) >= 3:
                d_, lo, hi, p = paired_bootstrap_diff(a[common].to_numpy(),
                                                      b[common].to_numpy())
                N.num("espVsIqaDiff", d_)
                N.num("espVsIqaLo", lo)
                N.num("espVsIqaHi", hi)
                N.num("espVsIqaP", p, "{:.4f}")
                N.num("espVsIqaN", len(common), "{:d}")

    # ---- 4. choosing an operator without labels --------------------------
    if not sel.empty:
        for name, key in (("Esp", "esp_mmd"), ("Identity", "identity"),
                          ("Oracle", "best_fixed_p1")):
            r = sel[sel.scorer == key].p1_regret
            N.pp(f"regret{name}", float(r.mean()) if len(r) else None)
        iqa_r = sel[sel.scorer.str.startswith("iqa_")]
        if len(iqa_r):
            by = iqa_r.groupby("scorer").p1_regret.mean()
            N.pp("regretIqaBest", by.min())
            N.pp("regretIqaWorst", by.max())
            N.word("regretIqaWorstName",
                   PRETTY_SCORE.get(by.idxmax(), by.idxmax()))
        esp_pick = sel[sel.scorer == "esp_mmd"]
        if len(esp_pick):
            N.num("espPicksIdentity",
                  int((esp_pick.picked == "identity").sum()), "{:d}")
            N.num("espPicksTotal", len(esp_pick), "{:d}")

    # ---- per-image reliability -------------------------------------------
    if not img.empty:
        a = img.groupby("scorer").auroc_p1_correct.mean()
        esp = a[a.index.str.startswith("esp_")]
        if len(esp):
            N.num("espAurocBest", esp.max())
            N.word("espAurocBestName", esp.idxmax().replace("esp_", ""))
        iqa = a[a.index.str.startswith("iqa_")]
        if len(iqa):
            N.num("iqaAurocBest", iqa.max())

    # ---- degradation axis -------------------------------------------------
    if not sev.empty:
        d = sev[(sev.dataset == "turbid_fish") & (sev.operator == "identity")]
        if not d.empty:
            m = d.groupby("severity").p1_accuracy.mean()
            N.pp("fishAccClear", m.iloc[0])
            N.pp("fishAccTurbid", m.iloc[-1])

        # does enhancement earn its place once conditions get bad enough?
        for ds, g in sev.groupby("dataset"):
            t = TAG.get(ds, ds)
            piv = g.groupby(["severity", "operator"]).p1_accuracy.mean().unstack()
            if "identity" not in piv.columns:
                continue
            delta = piv.sub(piv["identity"], axis=0).drop(columns="identity")
            N.num(f"sev{t}Levels", len(piv), "{:d}")
            N.num(f"sev{t}IdentityBest",
                  int((piv.idxmax(axis=1) == "identity").sum()), "{:d}")
            N.pp(f"sev{t}PenaltyMild", float(delta.mean(axis=1).iloc[0]))
            N.pp(f"sev{t}PenaltySevere", float(delta.mean(axis=1).iloc[-1]))
            if len(piv) >= 4:
                rho = spearmanr(piv.index.to_numpy(float),
                                delta.mean(axis=1).to_numpy()).statistic
                N.num(f"sev{t}Trend", float(rho))

    # ---- beyond the linear probe -----------------------------------------
    ft = read("finetune__*.csv")
    if not ft.empty:
        a = ft[ft.protocol == "P1_dropin"].set_index("operator").accuracy
        if "identity" in a.index:
            N.pp("ftIdentity", a["identity"])
            N.pp("ftWorst", a.min())
            N.word("ftWorstOp", PRETTY_OP.get(a.idxmin(), a.idxmin()))
            N.pp("ftDrop", a["identity"] - a.min())
            other = a.drop("identity")
            N.num("ftNHurt", int((other < a["identity"]).sum()), "{:d}")
            N.num("ftNOps", len(other), "{:d}")
            b = ft[ft.protocol == "P2_retrained"].set_index("operator").accuracy
            both = b.index.intersection(a.index).drop("identity", errors="ignore")
            if len(both):
                gap = (b[both] - a[both])
                N.pp("ftProtocolGap", float(gap.mean()))
                N.pp("ftGapMax", float(gap.max()))
                N.word("ftGapMaxOp", PRETTY_OP.get(gap.idxmax(), gap.idxmax()))
                # the clearest reversal: worse than nothing as a front end,
                # better than nothing once the network is refitted on it
                flip = [o for o in both
                        if a[o] < a["identity"] < b[o]]
                if flip:
                    o = max(flip, key=lambda k: b[k] - a["identity"])
                    N.word("ftReversedOp", PRETTY_OP.get(o, o))
                    N.pp("ftReversedPOne", float(a[o]))
                    N.pp("ftReversedPTwo", float(b[o]))
                    N.pp("ftReversedBelow", float(a["identity"] - a[o]))
                    N.pp("ftReversedVsIdentity", float(b[o] - a["identity"]))
                    N.num("ftNReversed", len(flip), "{:d}")
                # an operator that retraining cannot rescue has destroyed, not
                # merely moved, the information
                stuck = gap[gap < 0]
                if len(stuck):
                    N.word("ftStuckOp", PRETTY_OP.get(stuck.idxmin(), stuck.idxmin()))
                    N.pp("ftStuckGap", float(stuck.min()))
                    N.pp("ftStuckP2", float(b[stuck.idxmin()]))
                N.num("ftNP2", len(both), "{:d}")

    det = read("detection.csv")
    if not det.empty and "identity" in set(det.operator):
        m = det.set_index("operator").mAP50
        N.pp("detIdentity", m["identity"])
        N.pp("detWorst", m.min())
        N.word("detWorstOp", PRETTY_OP.get(m.idxmin(), m.idxmin()))
        N.pp("detDrop", m["identity"] - m.min())
        other = m.drop("identity")
        N.num("detNHurt", int((other < m["identity"]).sum()), "{:d}")
        N.num("detNOps", len(other), "{:d}")
        N.num("detImages", int(det.n_images.iloc[0]), "{:d}")
        # how closely do three unrelated models agree on which operator is worst?
        probe = (acc[acc.protocol == "P1_dropin"]
                 .query("dataset == 'exdark'")
                 .groupby("operator").accuracy.mean())
        common = m.index.intersection(probe.index)
        if len(common) >= 5:
            N.num("detVsProbeRho", spearmanr(m[common], probe[common]).statistic)
        if not ft.empty:
            a = ft[ft.protocol == "P1_dropin"].set_index("operator").accuracy
            c2 = m.index.intersection(a.index)
            if len(c2) >= 5:
                N.num("detVsFtRho", spearmanr(m[c2], a[c2]).statistic)
                N.num("ftVsProbeRho",
                      spearmanr(a[a.index.intersection(probe.index)],
                                probe[a.index.intersection(probe.index)]).statistic)

    # ---- is the penalty a tuning accident? --------------------------------
    sens = read("sensitivity__*.csv")
    if not sens.empty:
        N.num("sensN", len(sens), "{:d}")
        N.num("sensNBetter", int((sens.delta > 0).sum()), "{:d}")
        N.num("sensFamilies", sens.family.nunique(), "{:d}")
        N.pp("sensIdentity", float(sens.identity.iloc[0]))
        N.pp("sensBest", float(sens.accuracy.max()))
        N.pp("sensWorst", float(sens.accuracy.min()))
        N.word("sensWorstName", sens.loc[sens.accuracy.idxmin(), "variant"]
               .replace("_", " "))
        N.word("sensBestName", sens.loc[sens.accuracy.idxmax(), "variant"]
               .replace("_", " "))
        N.pp("sensBestGap", -float(sens.delta.max()))
        N.pp("sensWorstGap", -float(sens.delta.min()))

    # ---- the failure, counted --------------------------------------------
    qual = read("qualitative.csv")
    if not qual.empty:
        r = qual.iloc[0]
        N.num("qualBroken", int(r.n_broken_by_better_looking), "{:d}")
        N.num("qualTest", int(r.n_test), "{:d}")
        N.pp("qualFraction", float(r.fraction))

    # ---- splitting --------------------------------------------------------
    if not leak.empty:
        N.pp("leakageGap", float(leak.inflation.mean()))
        N.pp("leakageBlind", float(leak.group_blind.mean()))
        N.pp("leakageAware", float(leak.group_aware.mean()))

    N.write(OUT)


if __name__ == "__main__":
    main()
